def make_proposal(job: dict, cfg: dict) -> str:
    ev = job["eval"]
    cat = ev.get("category") or "海外企業・業界の調査レポート"
    name = cfg.get("display_name", "")
    exp = EXPERIENCE.get(cat, EXPERIENCE["海外企業・業界の調査レポート"])
    steps = STEPS.get(cat, STEPS["海外企業・業界の調査レポート"])
    question = QUESTIONS.get(cat, QUESTIONS["海外企業・業界の調査レポート"])

    lines = [
        f"はじめまして。ニューヨーク在住の{name}と申します。",
        f"「{job['title']}」の募集を拝見し、ご提案いたします。",
        "",
        "【関係する経験】",
        *[f"・{e}" for e in exp],
        "",
        "【進め方】",
        *[f"{i}. {s}" for i, s in enumerate(steps, 1)],
        "",
        "【納期・金額】",
        f"・納期: ご依頼から{ev['days']}日ほど",
        f"・{'時給' if job['budget']['type'] == 'hourly' else '金額'}: {ev['price']:,}円",
        f"・修正: {cfg.get('revisions_included', 2)}回まで含みます",
        "",
        "【確認したいこと】",
        f"・{question}",
        "",
        "ニューヨークとの時差がありますが、日本時間の朝と夜にご連絡しやすいです。",
        "どうぞよろしくお願いいたします。",
    ]
    return "\n".join(lines)
